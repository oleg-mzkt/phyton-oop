# Можно использовать метаклассы для создания экземляров и связи их с соответсвующими атрибутами(полями) 
# например class Women(models.Model):
# атрибуты: 
#  title
#  content
#  photo
#  time_create  и др.
# т.е. при создании объекта w=Women(title='Ума Турман') , 
# автоматически будут созданы content, photo, time_create  и др.

# попробуем создать такой класс Women и вложенные метакласскласс Meta(type):
class Meta(type):
    def create_local_attrs(self, *args, **kwargs):
        for key, value in self.class_attrs.items(): 
            self.__dict__[key] = value    
        #  .items() dозвращает представление словаря в виде последовательности кортежей (ключ: значение)
    
    def __init__(cls, name, bases, attrs):
        cls.class_attrs = attrs
        cls.__init__ = Meta.create_local_attrs
        
class Women(metaclass = Meta):
    title = 'заголовок'
    content = 'контент'
    photo = 'путь к фото'
    # Пользователь через ф-ции может сколько угодно добавлять новых атрибутов - логика не поменяется, больше нигде ничего не надо прописывать - всё будет автоматически

w = Women()
print(w.__dict__)
#>>> {'__module__': '__main__', '__qualname__': 'Women', 'title': 'заголовок', 'content': 'контент', 'photo': 'путь к фото'}
# т.е. автоматичекки созданы  локальный свойства:
#'title': 'заголовок'
#'content': 'контент'
#'photo': 'путь к фото'

