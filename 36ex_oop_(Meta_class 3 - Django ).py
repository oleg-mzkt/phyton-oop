#################2######через функцию############## 
# т.е. используя метакласс Meta следующие записи класса Women превращает класс Women в более универсальный формат: 

# ниже приведённые записи аналогичны тому что делают метаклассы, только не универсальный формат.
class Women:
    class_attrs = {'title': 'заголовок', 'content': 'контент', 'photo': 'путь к фото'}
    title = 'заголовок'
    content = 'контент'
    photo = 'путь к фото'
    # чтобы можно было добавить новый аттрибут Пользователем - необходимо зараанее прописать в class_attrs этот атрибут, что делает это гораздо сложне чем через класс
    
    def __init__(self,*args,**kwargs):
        for key, value in self.class_attrs.items():
            self.__dict__[key] = value # эта строчка как раз и формирует локальные свойства экз.класса Women 'title': 'заголовок' и т.д. 
w = Women()
print(w.__dict__)
#>>> {'title': 'заголовок', 'content': 'контент', 'photo': 'путь к фото'}
# получилось практически тоже самое, но чуть меньше атрибутов т.к. не исп. Meta

